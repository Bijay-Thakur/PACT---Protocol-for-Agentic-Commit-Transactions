"""Explicit enumerations for every PACT protocol concept.

No boolean ``success`` flags are used anywhere in the protocol: each lifecycle is
represented by an explicit state from one of these enums.
"""

from __future__ import annotations

from enum import StrEnum


class TransactionState(StrEnum):
    CREATED = "CREATED"
    SPECIFYING = "SPECIFYING"
    PREPARING = "PREPARING"
    PREPARED = "PREPARED"
    COMMITTING = "COMMITTING"
    VERIFYING = "VERIFYING"
    COMMITTED_VERIFIED = "COMMITTED_VERIFIED"
    ABORTING = "ABORTING"
    ABORTED = "ABORTED"
    UNKNOWN = "UNKNOWN"
    RECONCILING = "RECONCILING"
    COMPENSATING = "COMPENSATING"
    COMPENSATED = "COMPENSATED"
    HUMAN_REQUIRED = "HUMAN_REQUIRED"
    FAILED_TERMINAL = "FAILED_TERMINAL"


class EffectState(StrEnum):
    PROPOSED = "PROPOSED"
    VALIDATED = "VALIDATED"
    PREPARED = "PREPARED"
    DISPATCHING = "DISPATCHING"
    DISPATCHED = "DISPATCHED"
    VERIFYING = "VERIFYING"
    VERIFIED = "VERIFIED"
    UNKNOWN = "UNKNOWN"
    RECONCILING = "RECONCILING"
    RETRYABLE = "RETRYABLE"
    FAILED = "FAILED"
    COMPENSATING = "COMPENSATING"
    COMPENSATED = "COMPENSATED"
    HUMAN_REQUIRED = "HUMAN_REQUIRED"
    # Never dispatched; released because the transaction aborted or entered
    # recovery before this effect crossed into execution (see ADR-0004).
    ABORTED = "ABORTED"


