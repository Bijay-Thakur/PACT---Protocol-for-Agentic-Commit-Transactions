class VerificationStrategy(StrEnum):
    QUERY_BY_IDEMPOTENCY_KEY = "QUERY_BY_IDEMPOTENCY_KEY"
    QUERY_TARGET_STATE = "QUERY_TARGET_STATE"


class CompensationStrategy(StrEnum):
    NONE = "NONE"
    INVERSE_OPERATION = "INVERSE_OPERATION"
